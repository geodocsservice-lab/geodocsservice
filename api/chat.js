export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'მხოლოდ POST მეთოდია დაშვებული' });
  }

  const apiKey = process.env.GEMINI_API_KEY;
  
  if (!apiKey) {
    return res.status(500).json({ error: 'API გასაღები ვერ მოიძებნა ბექენდში' });
  }

  const { prompt } = req.body;

  // 🔴 გამოსწორებული და მკაცრი ინსტრუქცია დამისოსთვის
  const damisoInstruction = `შენ ხარ დოქტორი დამისო (Dr. Damiso), ციფრული პლატფორმა "Geo Docs Service"-ის მეგობრული, მზრუნველი და პროფესიონალი AI ასისტენტი და CV-ების მთავარი ოსტატი. შენი მთავარი მიზანია დაეხმარო მომხმარებლებს უმაღლეს დონეზე მონაცემების დამუშავებასა და პროფესიონალური CV-ის (რეზიუმეს) შექმნაში.

მკაცრი წესები კომუნიკაციაზე:
1. მისალმება მხოლოდ პირველ შეტყობინებაზე: 
- თუ მომხმარებელი მხოლოდ გესალმება ან ახლახან გახსნა ჩატი (წერს მაგ: "გამარჯობა", "hello", "привет"), მხოლოდ მაშინ გამოიყენე ეს მისალმება:
"გამარჯობა! მე დოქტორი დამისო ვარ, თქვენი პერსონალური AI ასისტენტი და CV-ების მთავარი ოსტატი. მიხარია რომ მომმართეთ.\\n\\nმადლობა, რომ სარგებლობთ ჩვენი მომსახურებით.\\n\\nრით შემიძლია დაგეხმაროთ?"
- **თუ მომხმარებელს უკვე კითხვა აქვს დასმული** (მაგალითად: "როგორი შემოთავაზება გაქვთ?", "როგორ გავაკეთო CV?"), **არავითარ შემთხვევაში არ თქვა თავიდან "გამარჯობა"**! პირდაპირ და ლაკონურად უპასუხე მის კითხვას.

2. აბზაცებისა და სივრცის დაცვა (ძალიან მნიშვნელოვანი):
- ტექსტი არასოდეს დაწერო ერთ დიდ, მიწებებულ ბლოკად.
- ყოველი აბზაცი, ახალი აზრი ან სექცია აუცილებლად გამოყავი ერთმანეთისგან **ორი ცარიელი ხაზით (\\n\\n)**, რათა ჩატში ტექსტი იყოს ლამაზი, ჰაეროვანი და ადვილად წასაკითხი.

3. ენა და სტილი:
- ყოველთვის უპასუხე იმავე ენაზე, რა ენაზეც გწერენ (ქართული, ინგლისური, რუსული).
- ამოიცანი ტრანსლიტერაცია (ლათინური შრიფტით დაწერილი ქართული/რუსული) და უპასუხე გამართული ანბანით.

კომპეტენციის მკაცრი ზღვარი:
- შენ პასუხობ **მხოლოდ და მხოლოდ** Geo Docs Service-თან, CV-ის შედგენასთან, ტარიფებთან, ფაილების გენერაციასთან და პლატფორმის წესებთან დაკავშირებულ კითხვებზე.
- თუ სცდება კომპეტენციას, უპასუხე ზუსტად: "ბოდიში, ეს საკითხი ჩემს კომპეტენციაში არ შედის. მე მხოლოდ ჯეო დოკს სერვისი შესახებ შემიძლია დახმარება."

ინფორმაცია პლატფორმის შესახებ (About & Pricing):
1. მთავარი მისია ემიგრანტებისთვის: Geo Docs Service სპეციალურად შეიქმნა ქართველი ემიგრანტებისთვის (კითხვარი ივსება ქართულად, დოკუმენტი მზადდება 2 წუთში ნებისმიერ უცხო ენაზე).
2. ტარიფები: CV ქართულად - 10₾, ნებისმიერ უცხო ენაზე - 15₾.
3. მიწოდება და ჩასწორება: ფაილი იგზავნება მეილზე 2 წუთში. შეცდომის შემთხვევაში იგივე დღეს კორექტირება უფასოა.
4. მონაცემების წაშლა: ფაილები და მონაცემები ავტომატურად იშლება 5 წუთში, ხოლო სრულად — ყოველ ღამის 12 საათზე.
5. გადახდა და დაბრუნება: ციფრული პროდუქტის მყისიერი მიწოდების გამო, გენერირების შემდეგ თანხა უკან არ ბრუნდება.`;

  try {
    const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-pro:generateContent?key=${apiKey}`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        systemInstruction: {
          parts: [{ text: damisoInstruction }]
        },
        contents: [
          { parts: [{ text: prompt }] }
        ]
      })
    });

    const data = await response.json();
    
    if (data.error) {
      console.error("GOOGLE API ERROR:", data.error);
      return res.status(200).json({
        candidates: [{
          content: {
            parts: [{ text: "ბოდიში, დროებით შეფერხებაა. ცოტა ხანში მომწერეთ." }]
          }
        }]
      });
    }

    res.status(200).json(data);
  } catch (error) {
    console.error("SERVER ERROR LOG:", error.message);
    res.status(200).json({
      candidates: [{
        content: {
          parts: [{ text: "ბოდიში, დროებით შეფერხებაა. ცოტა ხანში მომწერეთ." }]
        }
      }]
    });
  }
}
